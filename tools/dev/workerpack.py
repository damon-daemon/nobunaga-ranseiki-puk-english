#!/usr/bin/env python3
"""Assemble notes/worker_pack.md: the compact context a translation worker reads instead of
CLAUDE.md + the whole glossary + msg_vars.md + the pilot files (~100 KB -> ~12 KB).
Re-run after editing the glossary, the legend or the pilot. Sources:
  notes/glossary.md        sections Ranks .. Dialogue style (+ worker terms)
  notes/survey/msg_vars.md the SETTLED field-name section
  tl/message/0500.txt      pilot dialogue #600-#638 (tone sample)
"""
import re, sys, pathlib
R = pathlib.Path(__file__).resolve().parents[2]

def section(text, start_pat, end_pat):
    lines = text.splitlines()
    s = next(i for i, l in enumerate(lines) if re.match(start_pat, l))
    e = next((i for i, l in enumerate(lines) if i > s and re.match(end_pat, l)), len(lines))
    return '\n'.join(lines[s:e]).rstrip() + '\n'

gl = (R / 'notes/glossary.md').read_text()
mv = (R / 'notes/survey/msg_vars.md').read_text()
pilot = (R / 'tl/message/0500.txt').read_text()

parts = ['# Worker pack (generated by tools/dev/workerpack.py — do not edit)\n',
         '# 1. Glossary extracts\n',
         section(gl, r'^## Ranks', r'^## Terms from the translation workers'),
         section(gl, r'^## Terms from the translation workers', r'^## ELF UI terms'),
         '# 2. Message variables (settled field names)\n',
         section(mv, r'^## SETTLED', r'^## How the interpreter'),
         section(mv, r'^## Notes for translators', r'^## Open questions'),
         '# 3. Pilot tone sample (tl/message/0500.txt, dialogue #600-#638)\n```\n',
         section(pilot, r'^@600\b', r'^@(61[6-9]|6[2-9]\d|[7-9]\d\d|\d{4,})\b'), '```\n']
out = '\n'.join(parts)
(R / 'notes/worker_pack.md').write_text(out)
print('notes/worker_pack.md: %d bytes' % len(out.encode()))
